"""Scene, location, insertion and clipboard regressions in an isolated browser."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
import os

ROOT=Path(__file__).resolve().parents[1]
with sync_playwright() as p:
    executable=os.environ.get('CHROMIUM_PATH') or ('/usr/bin/chromium' if Path('/usr/bin/chromium').exists() else None)
    browser=p.chromium.launch(executable_path=executable,headless=True,args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1360,'height':1000})
    page.set_default_timeout(12000)
    errors=[]
    page.on('pageerror',lambda error:errors.append(str(error)))
    page.goto(os.environ.get('APP_URL','http://127.0.0.1:1420'))
    page.locator('#file-input').set_input_files(str(ROOT/'examples/示例剧本.story.json'))
    page.locator('[data-act="locations"]').click()
    page.locator('[data-act="add-location"]').first.click()
    page.locator('#location-name').fill('旧书房')
    page.locator('#location-bgm').fill('雨夜.ogg')
    page.locator('#location-background').fill('旧书房.webp')
    page.locator('#location-ambience').fill('雨声')
    page.locator('#location-properties').fill('时间 = 夜晚\n楼层 = 二楼')
    page.locator('#location-save').click()
    expect(page.locator('.location-card')).to_have_count(1)
    location_id=page.evaluate('window.XuXian.snapshot().locations[0].id')
    page.locator('[data-act="board"]').click()
    page.locator('[data-act="open-chapter"][data-id="chapter_a1"]').click()
    page.locator('[data-act="open-stage"][data-id="stage_a1_1"]').click()
    page.locator('[data-row="line_1"] > .row-number > .row-select').click()
    page.locator('[data-row="line_2"] > .row-number > .row-select').click(modifiers=['Shift'])
    page.keyboard.press('Control+g')
    expect(page.get_by_role('dialog',name='建立场景组')).to_be_visible()
    page.locator('#group-title').fill('书房初访')
    page.locator('#group-location').select_option(location_id)
    page.locator('#group-notes').fill('窗边的桌子，主角在门口')
    page.locator('#group-save').click()
    expect(page.locator('.group-row')).to_have_count(1)
    expect(page.locator('.scene-group-meta')).to_contain_text('BGM：雨夜.ogg')
    expect(page.locator('.scene-group-meta')).to_contain_text('时间：夜晚')
    group_id=page.evaluate('window.XuXian.snapshot().chapters[0].stages[0].rows[0].id')
    page.locator('[data-row="line_1"] textarea[data-row-field="text"]').fill('分组后的对白仍可编辑')
    assert page.evaluate('window.XuXian.snapshot().chapters[0].stages[0].rows[0].rows[0].text')=='分组后的对白仍可编辑'
    # Right-click insertion uses the clicked row and its immediate container.
    page.locator('[data-row="line_1"] > .row-number').click(button='right')
    page.get_by_role('menuitem',name='在上方插入',exact=True).click()
    page.get_by_role('menuitem',name='描述',exact=True).click()
    assert page.evaluate('window.XuXian.snapshot().chapters[0].stages[0].rows[0].rows[0].type')=='effect'
    page.locator('[data-row="line_2"] > .row-number').click(button='right')
    page.get_by_role('menuitem',name='在下方插入',exact=True).click()
    page.get_by_role('menuitem',name='对白',exact=True).click()
    grouped=page.evaluate('window.XuXian.snapshot().chapters[0].stages[0].rows[0].rows')
    assert grouped[-1]['speakerId']==grouped[-2]['speakerId']=='char_protagonist'
    page.locator('.scene-group-title').click()
    page.locator('#group-override-bgm').check()
    page.locator('#group-value-bgm').fill('紧张.ogg')
    page.locator('#group-override-properties').check()
    page.locator('#group-properties').fill('时间 = 深夜')
    page.locator('#group-save').click()
    expect(page.locator('.scene-group-meta')).to_contain_text('紧张.ogg · 本组')
    expect(page.locator('.scene-group-meta')).to_contain_text('时间：深夜')
    # Group collapse, ungroup, undo and typed copying preserve the complete tree.
    page.locator('.scene-group-toggle').click()
    expect(page.locator('.scene-group-content')).to_be_hidden()
    page.locator('.scene-group-toggle').click()
    page.locator('[data-act="group-menu"]').click()
    page.get_by_role('menuitem',name='取消分组，保留内容',exact=True).click()
    expect(page.locator('.group-row')).to_have_count(0)
    page.keyboard.press('Control+z')
    expect(page.locator('.group-row')).to_have_count(1)
    page.locator('.group-select').click()
    page.locator('[data-act="copy-rows"]').click()
    page.locator('#open-btn').click()
    page.locator('#library-create').click()
    page.locator('#library-new-name').fill('跨项目复制测试')
    page.locator('#library-new-submit').click()
    page.locator('#replace-discard').click()
    project=page.evaluate('window.XuXian.snapshot()')
    chapter=project['chapters'][0]
    page.locator(f'[data-act="open-chapter"][data-id="{chapter["id"]}"]').click()
    page.locator(f'[data-act="open-stage"][data-id="{chapter["stages"][0]["id"]}"]').click()
    page.locator('[data-act="script-menu"]').click()
    page.get_by_role('menuitem',name='粘贴对白行',exact=True).click()
    expect(page.locator('.group-row')).to_have_count(1)
    copied=page.evaluate('window.XuXian.snapshot()')
    copied_group=copied['chapters'][0]['stages'][0]['rows'][0]
    assert copied_group['id']!=group_id
    assert copied['locations'][0]['name']=='旧书房'
    assert copied_group['locationId']==copied['locations'][0]['id']
    assert copied_group['overrides']['bgm']=='紧张.ogg'
    assert copied['version']==7
    # JSON export contains the full new schema; reopening restores it.
    page.locator('#menu-btn').click()
    with page.expect_download() as event:
        page.get_by_role('menuitem',name='下载源文件副本',exact=True).click()
    exported=ROOT/'work/test-results/scenes-export.story.json'
    exported.parent.mkdir(parents=True,exist_ok=True)
    event.value.save_as(str(exported))
    page.reload()
    page.locator('#file-input').set_input_files(str(exported))
    page.locator(f'[data-act="open-chapter"][data-id="{chapter["id"]}"]').click()
    page.locator(f'[data-act="open-stage"][data-id="{chapter["stages"][0]["id"]}"]').click()
    expect(page.locator('.group-row')).to_have_count(1)
    expect(page.locator('.scene-group-meta')).to_contain_text('时间：深夜')
    page.locator('#menu-btn').click()
    page.get_by_role('menuitem',name='地点预设',exact=True).click()
    page.locator('.location-card').click()
    page.locator('#location-delete').click()
    expect(page.get_by_role('dialog',name='编辑地点')).to_be_visible()
    expect(page.locator('#toast')).to_contain_text('仍有 1 处引用')
    page.locator('#location-bgm').fill('修改后的默认 BGM')
    page.locator('#location-ambience').fill('远处雷声')
    page.locator('#location-save').click()
    page.locator('[data-act="board"]').click()
    page.locator(f'[data-act="open-chapter"][data-id="{chapter["id"]}"]').click()
    page.locator(f'[data-act="open-stage"][data-id="{chapter["stages"][0]["id"]}"]').click()
    expect(page.locator('.scene-group-meta')).to_contain_text('紧张.ogg · 本组')
    expect(page.locator('.scene-group-meta')).to_contain_text('远处雷声')
    page.locator('.scene-group-toggle').click()
    page.locator('#search-btn').click()
    page.locator('#search-input').fill('分组后的对白仍可编辑')
    page.locator('.search-item').first.click()
    expect(page.locator('.scene-group-content')).to_be_visible()
    expect(page.locator('.scene-group-rows textarea.dialogue-cell').first).to_have_value('分组后的对白仍可编辑')
    page.locator('#menu-btn').click()
    with page.expect_download() as markdown_event:
        page.get_by_role('menuitem',name='导出可读剧本',exact=True).click()
    markdown=ROOT/'work/test-results/scenes-export.md'
    markdown_event.value.save_as(str(markdown))
    exported_markdown=markdown.read_text()
    assert all(value in exported_markdown for value in ['书房初访','旧书房','紧张.ogg','时间：深夜','窗边的桌子'])
    # Group within one choice option remains separate from other options.
    page.locator('#file-input').set_input_files(str(ROOT/'examples/示例剧本.story.json'))
    page.locator('#replace-discard').click()
    page.locator('[data-act="open-chapter"][data-id="chapter_a1"]').click()
    page.locator('[data-act="open-stage"][data-id="stage_a1_1"]').click()
    page.locator('[data-branch-row="line_local_a1"] .row-select').click()
    page.locator('[data-branch-row="line_local_a2"] .row-select').click(modifiers=['Shift'])
    page.keyboard.press('Control+g')
    page.locator('#group-title').fill('选项内的场景')
    page.locator('#group-save').click()
    expect(page.locator('.local-option .group-row')).to_have_count(1)
    page.locator('[data-branch-row="line_local_a1"] [data-branch-field="text"]').fill('选项内分组编辑')
    page.locator('[data-act="open-stage"][data-id="stage_a1_investigation"]').click()
    page.locator('.inspect-open').first.click()
    page.locator('.investigation-writing [data-act="add-row"]').click()
    picks=page.locator('.investigation-writing .script-row .row-select')
    picks.nth(0).click()
    picks.nth(1).click(modifiers=['Shift'])
    page.keyboard.press('Control+g')
    page.locator('#group-title').fill('调查信封')
    page.locator('#group-save').click()
    expect(page.locator('.investigation-writing .group-row')).to_have_count(1)
    page.screenshot(path=str(ROOT/'work/test-results/scene-groups.png'),full_page=True)
    # A whole group is one sortable unit; its children remain in order.
    page.locator('.investigation-writing .scene-group-toggle').click()
    group=page.locator('.investigation-writing .group-row')
    group.scroll_into_view_if_needed()
    source=group.locator('.group-select').bounding_box()
    target=group.locator('xpath=following-sibling::*[1]').bounding_box()
    if target:
        page.mouse.move(source['x']+source['width']/2,source['y']+source['height']/2)
        page.mouse.down()
        page.mouse.move(source['x']+source['width']/2+12,source['y']+source['height']/2+10)
        page.mouse.move(source['x']+source['width']/2+12,target['y']+target['height']+5,steps=8)
        page.mouse.up()
        investigation=page.evaluate('window.XuXian.snapshot().chapters[0].stages.find(stage=>stage.id==="stage_a1_investigation")')
        assert investigation['objects'][0]['rows'][0]['type']!='group'
        assert len(next(row for row in investigation['objects'][0]['rows'] if row['type']=='group')['rows'])==2
    assert not errors,errors
    browser.close()
    print('PASS: location presets, groups, metadata inheritance/overrides, right-click insertion, copy, JSON restore, option and investigation groups')
